-- MySQL 8.0 migration for the appointment minimum loop.
-- Run only after backing up the database and reviewing the two preflight queries below.
-- This file changes schema metadata only; it does not delete or rewrite business rows.

-- The result must be empty before adding one schedule row per doctor and date.
SELECT doctor_id, date, COUNT(*) AS duplicate_count
FROM dates
GROUP BY doctor_id, date
HAVING COUNT(*) > 1;

-- The result must be empty before enforcing one occupied reservation per slot.
SELECT doctor_id, appointment_date, appointment_time, COUNT(*) AS duplicate_count
FROM appointments
WHERE status IN ('booked', 'completed')
GROUP BY doctor_id, appointment_date, appointment_time
HAVING COUNT(*) > 1;

-- appointment_id is generated by MySQL; service code must never use MAX(id) + 1.
ALTER TABLE appointments
    MODIFY COLUMN appointment_id INT NOT NULL AUTO_INCREMENT;

ALTER TABLE dates
    ADD CONSTRAINT uk_dates_doctor_date UNIQUE (doctor_id, date);

-- MySQL has no partial unique index. NULL is allowed repeatedly in a unique index,
-- so this generated key permits retained cancelled/completed history while allowing
-- only one occupied reservation for a doctor/date/slot.
ALTER TABLE appointments
    ADD COLUMN active_slot_key VARCHAR(128)
        GENERATED ALWAYS AS (
            CASE WHEN status IN ('booked', 'completed')
                 THEN CONCAT(doctor_id, '|', appointment_date, '|', appointment_time)
                 ELSE NULL
            END
        ) STORED,
    ADD CONSTRAINT uk_appointments_active_slot UNIQUE (active_slot_key);
